#!/usr/bin/env bash
#
# Smoke tests for MeowLauncherCli.
#
# Usage:
#   ./scripts/test.sh
#
# Builds the binary via scripts/build.sh, then checks the basic CLI contract:
# help output, version output, exit codes, locale selection, and per-module
# unit tests. Emits a JUnit report to build_test/junit.xml for Codecov test
# analytics.

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT"

# Deterministic language: expect the English archive regardless of the
# runner's system locale.
export LANG=C

# Match the binary name produced by build.sh on this platform.
case "$(uname -s)" in
    MINGW*|MSYS*|CYGWIN*) bin_suffix=".exe" ;;
    *) bin_suffix="" ;;
esac

echo "[INFO] Building test binary..."
test_dir="$PROJECT_ROOT/build_test"
mkdir -p "$test_dir"

CC="${CC:-gcc}"
CFLAGS="${CFLAGS:--std=c11 -Wall -Wextra -Wpedantic -D_POSIX_C_SOURCE=200809L -I.}"
echo "[INFO] Compiler: $CC"
if [ "${COVERAGE:-0}" = "1" ]; then
    CFLAGS="$CFLAGS --coverage"
fi
GIT_VERSION="${GIT_VERSION:-$(git rev-parse HEAD 2>/dev/null || echo unknown)}"
CFLAGS="$CFLAGS -DGIT_VERSION=\"$GIT_VERSION\""

SOURCES=()
while IFS= read -r f; do SOURCES+=("$f"); done < <(find . -name '*.c' -not -path './.git/*' -not -path './tests/*')
njobs="$(nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo 4)"
BIN="$test_dir/meowlaunchcli${bin_suffix}"
status=0

# Collect "PASS|name" / "FAIL|name" rows; rendered into JUnit XML at exit.
results=()

check() {
    local name="$1"; shift
    if "$@" >/dev/null 2>&1; then
        results+=("PASS|$name")
    else
        echo "[FAIL] $name"
        results+=("FAIL|$name")
        status=1
    fi
}

# Rebuild binary with restricted LANGS, output to test_dir only (never build/).
rebuild() {
    local langs="$1"
    local gen_header="$PROJECT_ROOT/internal/i18n/gen/lang_embedded.h"
    mkdir -p "$(dirname "$gen_header")"
    local wanted=()
    if [ -n "$langs" ]; then
        for l in $langs; do wanted+=("$PROJECT_ROOT/lang/$l.json"); done
    else
        wanted=()
        while IFS= read -r f; do wanted+=("$f"); done < <(find "$PROJECT_ROOT/lang" -maxdepth 1 -name '*.json' | sort)
    fi
    local ordered=()
    [ -f "$PROJECT_ROOT/lang/en.json" ] && ordered+=("$PROJECT_ROOT/lang/en.json")
    for src in "${wanted[@]}"; do
        [ "$(basename "$src" .json)" = "en" ] && continue
        [ -f "$src" ] && ordered+=("$src")
    done
    {
        echo "/* Generated by test.sh from the lang/ archives. Do not edit. */"
        echo "static const struct { const char *prefix; const char *json; } builtin_langs[] = {"
        for src in "${ordered[@]}"; do
            local name prefix prefix_c
            name="$(basename "$src" .json)"
            prefix="${name%%-*}"
            if [ "$name" = "en" ]; then prefix_c="NULL"; else prefix_c="\"$prefix\""; fi
            local escaped
            escaped="$(sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' "$src" | awk 'BEGIN{ORS="\\n"} {print}')"
            printf '    { %s, "%s" },\n' "$prefix_c" "$escaped"
        done
        echo "};"
        printf '#define BUILTIN_LANGS_COUNT %d\n' "${#ordered[@]}"
    } > "$gen_header"

    local obj_dir="$test_dir/obj"
    mkdir -p "$obj_dir"
    rm -f "$obj_dir"/*.o
    local objs=()
    for src in "${SOURCES[@]}"; do
        objs+=("$obj_dir/$(echo "$src" | sed 's|/|_|g;s|\.c$|.o|')")
    done
    printf '%s\n' "${SOURCES[@]}" | CC="$CC" CFLAGS="$CFLAGS" obj_dir="$obj_dir" \
        xargs -P "$njobs" -I{} sh -c \
        '"$CC" $CFLAGS -c "$1" -o "$obj_dir/$(echo "$1" | sed "s|/|_|g;s|\.c$|.o|")"' _ {} || { echo "[ERROR] parallel compile failed"; exit 1; }
    "$CC" $CFLAGS "${objs[@]}" -o "$BIN" || { echo "[ERROR] link failed"; exit 1; }
}

# Initial build: all languages embedded.
rebuild ""

# 1. No arguments: prints help, exits 0.
out="$("$BIN")"
echo "$out" | grep -q "Usage: meowlaunchcli" \
    && check "bare invocation prints help" true \
    || { echo "[FAIL] bare invocation missing usage line"; results+=("FAIL|bare invocation prints help"); status=1; }

# 2. help subcommand: exits 0.
check "help subcommand exits 0" "$BIN" help

# 3. version: matches "MeowLauncherCli v<semver> build <git>".
out="$("$BIN" version)"
echo "$out" | grep -Eq "^MeowLauncherCli v[0-9]+\.[0-9]+\.[0-9]+ build .+" \
    && check "version output format" true \
    || { echo "[FAIL] unexpected version output: $out"; results+=("FAIL|version output format"); status=1; }

# 4. Unknown command: exits nonzero.
if "$BIN" doesnotexist >/dev/null 2>&1; then
    echo "[FAIL] unknown command exited 0"
    results+=("FAIL|unknown command nonzero exit")
    status=1
else
    results+=("PASS|unknown command nonzero exit")
fi

# 5. Locale detection: an unrelated system locale falls back to English.
LANG=fr_FR.UTF-8 "$BIN" | grep -q "Usage: meowlaunchcli" \
    && results+=("PASS|fr locale falls back to english") \
    || { echo "[FAIL] fr locale did not fall back to English"; results+=("FAIL|fr locale falls back to english"); status=1; }

# 6. zh_TW locale selects the zh-TW archive (default multi-language build).
LANG=zh_TW.UTF-8 "$BIN" | grep -q "指令：" \
    && results+=("PASS|zh_TW selects chinese") \
    || { echo "[FAIL] zh_TW locale did not select zh-TW help"; results+=("FAIL|zh_TW selects chinese"); status=1; }

# 7. ja_JP locale selects the Japanese archive.
LANG=ja_JP.UTF-8 "$BIN" | grep -q "コマンド:" \
    && results+=("PASS|ja_JP selects japanese") \
    || { echo "[FAIL] ja_JP locale did not select Japanese help"; results+=("FAIL|ja_JP selects japanese"); status=1; }

# 8. Single-language build (LANGS=en): any system locale still yields English.
echo "[INFO] Single-language build check..."
rebuild "en"
LANG=zh_TW.UTF-8 "$BIN" | grep -q "Usage: meowlaunchcli" \
    && results+=("PASS|single-lang build ignores locale") \
    || { echo "[FAIL] single-lang build ignored LANGS"; results+=("FAIL|single-lang build ignores locale"); status=1; }

# 9. Language not compiled in (LANGS=en ja-JP): zh locale falls back English.
echo "[INFO] Uncompiled-language fallback check..."
rebuild "en ja-JP"
LANG=zh_TW.UTF-8 "$BIN" | grep -q "Usage: meowlaunchcli" \
    && results+=("PASS|uncompiled language falls back to english") \
    || { echo "[FAIL] uncompiled zh locale did not fall back to English"; results+=("FAIL|uncompiled language falls back to english"); status=1; }

# 10. Unit tests: rebuild default all-languages binary back into test_dir.
echo "[INFO] Unit tests..."
rebuild ""
# Exercise the final coverage binary once so gcda matches this build.
"$BIN" help >/dev/null
"$BIN" version >/dev/null
"$BIN" account help >/dev/null
"$BIN" account local add covuser >/dev/null
"$BIN" account local del covuser >/dev/null
# Unit-test compiler: prefer gcc (present on Alpine, MinGW, Ubuntu).
if [ -z "${CC:-}" ]; then
    if command -v gcc >/dev/null 2>&1; then CC="gcc"; else CC="cc"; fi
fi
CFLAGS="${CFLAGS:--std=c11 -Wall -Wextra -Wpedantic -D_POSIX_C_SOURCE=200809L -I.}"
if [ "${COVERAGE:-0}" = "1" ]; then
    CFLAGS="$CFLAGS --coverage"
fi
echo "[INFO] Compiler: $CC"
GIT_VERSION="${GIT_VERSION:-$(git rev-parse HEAD 2>/dev/null || echo unknown)}"
CFLAGS="$CFLAGS -DGIT_VERSION=\"$GIT_VERSION\""
for test_src in $(find tests -name 'test_*.c'); do
    mod="$(dirname "$test_src" | sed 's|tests/||')"
    unit_bin="$test_dir/test_$(echo "$mod" | tr '/' '_')${bin_suffix}"
    # Each test .c includes the source under test directly (or is a black-box
    # main), so no separate module link step is needed.
    # Per-test extra link flags: usersfile test wraps malloc to inject failure.
    extra_ld=""
    if [ "$(uname -s)" != "Darwin" ]; then
        case "$test_src" in
            *test_usersfile.c) extra_ld="-Wl,--wrap,malloc -Wl,--wrap,free" ;;
            *test_json_io.c) extra_ld="-Wl,--wrap,malloc" ;;
            *test_json_escape.c) extra_ld="-Wl,--wrap,malloc" ;;
            *test_game.c) extra_ld="-Wl,--wrap,malloc" ;;
        esac
    fi
    # shellcheck disable=SC2086
    if ! "$CC" $CFLAGS "$test_src" -o "$unit_bin" $extra_ld; then
        echo "[FAIL] build unit test $mod"
        results+=("FAIL|unit test $mod")
        status=1
        continue
    fi
    echo "[INFO] == $mod =="
    if MEOWLAUNCH_BIN="$BIN" "$unit_bin"; then
        results+=("PASS|unit test $mod")
    else
        echo "[FAIL] unit test $mod"
        results+=("FAIL|unit test $mod")
        status=1
    fi
done

# Emit JUnit XML for Codecov test analytics into build_test/.
junit="$test_dir/junit.xml"
{
    echo '<?xml version="1.0" encoding="UTF-8"?>'
    echo '<testsuites>'
    echo "  <testsuite name=\"meowlaunchcli\" tests=\"${#results[@]}\">"
    for row in "${results[@]}"; do
        state="${row%%|*}"
        name="${row#*|}"
        # XML-escape the name (only & < > matter for our names).
        esc="${name//&/&amp;}"
        esc="${esc//</&lt;}"
        esc="${esc//>/&gt;}"
        echo "    <testcase classname=\"smoke\" name=\"$esc\">"
        if [ "$state" = "FAIL" ]; then
            echo '      <failure/>'
        fi
        echo '    </testcase>'
    done
    echo '  </testsuite>'
    echo '</testsuites>'
} > "$junit"
echo "[INFO] JUnit report: $junit"

# Coverage build: emit HTML + cobertura into build_test/.
if [ "${COVERAGE:-0}" = "1" ]; then
    if command -v gcovr >/dev/null 2>&1; then
        gcovr -r "$PROJECT_ROOT" --html-details \
            --exclude '^tests/' --exclude '^build/' --exclude '^build_test/' \
            -o "$test_dir/coverage.html" "$test_dir"
        gcovr -r "$PROJECT_ROOT" --xml \
            --exclude '^tests/' --exclude '^build/' --exclude '^build_test/' \
            -o "$test_dir/coverage.xml" "$test_dir"
        echo "[INFO] Coverage report: $test_dir/coverage.html"
    else
        echo "[WARN] gcovr not found; using gcov directly"
        (cd "$test_dir" && gcov --preserve-paths *.gcno 2>/dev/null) || true
        echo "[INFO] gcov output: $test_dir/*.gcov"
    fi
fi

if [ "$status" -eq 0 ]; then
    echo "[INFO] All tests passed"
else
    echo "[ERROR] Tests failed"
fi

exit "$status"
