#!/usr/bin/env bash
#
# Build MeowLauncherCli.
#
# Usage:
#   ./scripts/build.sh
#
# Toolchain:
#   Linux           musl-gcc, statically linked (default)
#   Windows/MinGW   gcc (MSYS2), meowlaunchcli.exe
#
# Environment overrides:
#   CC           C compiler (auto-selected per platform, override if needed)
#   CFLAGS       extra compile flags
#   LDFLAGS      extra link flags (Linux default: -static)
#   GIT_VERSION  git build identifier (default: git describe --always --dirty)
#   LANGS        languages baked into the binary, space-separated
#                (default: "en zh-TW ja-JP"; e.g. LANGS="en" for one language)

set -euo pipefail

# Always build from the project root, regardless of the caller's directory.
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT"

# --- Toolchain selection -------------------------------------------------
bin_suffix=""
uname_s="$(uname -s)"
case "$uname_s" in
    Linux*)
        CC="${CC:-musl-gcc}"
        LDFLAGS="${LDFLAGS:--static}"
        ;;
    MINGW*|MSYS*|CYGWIN*)
        CC="${CC:-gcc}"
        LDFLAGS="${LDFLAGS:-}"
        bin_suffix=".exe"
        ;;
    *)
        echo "[WARN] Unknown platform '$uname_s', falling back to gcc" >&2
        CC="${CC:-gcc}"
        LDFLAGS="${LDFLAGS:-}"
        ;;
esac
CFLAGS="${CFLAGS:--std=c11 -Wall -Wextra -Wpedantic -D_POSIX_C_SOURCE=200809L -I.}"

# Git build identifier embedded into the "version" subcommand.
GIT_VERSION="${GIT_VERSION:-$(git describe --always --dirty 2>/dev/null || true)}"
GIT_VERSION="${GIT_VERSION:-unknown}"

# Languages baked into the binary at build time.
lang_defs=()
for lang in ${LANGS:-en zh-TW ja-JP}; do
    case "$lang" in
        en)    lang_defs+=("-DLANG_EN=1") ;;
        zh-TW) lang_defs+=("-DLANG_ZH_TW=1") ;;
        ja-JP) lang_defs+=("-DLANG_JA_JP=1") ;;
        *)     echo "[WARN] Unknown language '$lang', ignored" >&2 ;;
    esac
done

# Embed the selected lang/*.json archives as C string macros. Generated
# header: internal/i18n/gen/lang_embedded.h (add it to .gitignore).
gen_header="$PROJECT_ROOT/internal/i18n/gen/lang_embedded.h"
mkdir -p "$(dirname "$gen_header")"
{
    echo "/* Generated by scripts/build.sh from the lang/ archives. Do not edit. */"
    for lang in ${LANGS:-en zh-TW ja-JP}; do
        case "$lang" in
            en)     def="LANG_JSON_EN" ;;
            zh-TW)  def="LANG_JSON_ZH_TW" ;;
            ja-JP)  def="LANG_JSON_JA_JP" ;;
            *)      continue ;;
        esac
        src="$PROJECT_ROOT/lang/$lang.json"
        if [ ! -f "$src" ]; then
            echo "[WARN] $src missing, skipped" >&2
            continue
        fi
        # Escape backslashes and quotes, turn newlines into literal \n.
        escaped="$(sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' "$src" \
                   | awk 'BEGIN{ORS="\\n"} {print}')"
        printf '#define %s "%s"\n' "$def" "$escaped"
    done
} > "$gen_header"

# Collect every translation unit of the product (tests/ are not part of it).
mapfile -t SOURCES < <(find . -name '*.c' -not -path './.git/*' -not -path './tests/*')

echo "[INFO] Platform=$uname_s CC=$CC GIT_VERSION=$GIT_VERSION LANGS='${LANGS:-en zh-TW ja-JP}'"
echo "[INFO] Sources: ${SOURCES[*]}"

# Output directory: coverage builds keep every artifact (objects, .gcno/.gcda,
# binary) in build_test/; normal builds go to build/.
if [ "${COVERAGE:-0}" = "1" ]; then
    out_dir="$PROJECT_ROOT/build_test"
    CFLAGS="$CFLAGS --coverage"
else
    out_dir="$PROJECT_ROOT/build"
fi
mkdir -p "$out_dir"
out_bin="$out_dir/meowlaunchcli${bin_suffix}"

if [ "${COVERAGE:-0}" = "1" ]; then
    # Compile separate objects so .gcno/.gcda land in build_test/.
    objs=()
    idx=0
    for src in "${SOURCES[@]}"; do
        obj="$out_dir/obj_${idx}.o"
        # shellcheck disable=SC2086
        "$CC" $CFLAGS "${lang_defs[@]}" -DGIT_VERSION="\"$GIT_VERSION\"" \
            -c "$src" -o "$obj"
        objs+=("$obj")
        idx=$((idx + 1))
    done
    "$CC" --coverage "${objs[@]}" -o "$out_bin" $LDFLAGS
else
    # shellcheck disable=SC2086
    "$CC" $CFLAGS "${lang_defs[@]}" -DGIT_VERSION="\"$GIT_VERSION\"" \
        "${SOURCES[@]}" -o "$out_bin" $LDFLAGS
fi

echo "[INFO] Build OK: $out_bin"
